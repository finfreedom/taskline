test('сообщение появляется только после последней галочки и исчезает через 4 секунды', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const notice = page.getByTestId('completion-notice')
  await expect(notice).toHaveCount(0)
  for (const title of ['Первый шаг', 'Последний шаг']) {
    await page.getByRole('textbox').fill(title)
    await page.getByRole('textbox').press('Enter')
  }
  await page.getByRole('checkbox', { name: 'Первый шаг', exact: true }).check()
  await expect(notice).toHaveCount(0)
  await page.getByRole('button', { name: /^Активные/ }).click()
  // In the active filter this checkbox unmounts immediately; check() cannot verify it afterwards.
  await page.getByRole('checkbox', { name: 'Последний шаг', exact: true }).click()
  await expect(notice).toHaveText('Всё сделано. Отличная работа!')
  await expect(notice).toBeInViewport()
  await page.clock.fastForward(4100)
  await expect(notice).toHaveCount(0)
  await page.reload()
  await expect(notice).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Последний шаг', exact: true })).toBeChecked()
})

test('новая активная задача убирает сообщение, удаление и возврат не запускают его', async ({ page }) => {
  await page.goto('/')
  const notice = page.getByTestId('completion-notice')
  await page.getByRole('textbox').fill('Одна задача')
  await page.getByRole('textbox').press('Enter')
  const checkbox = page.getByRole('checkbox', { name: 'Одна задача', exact: true })
  await checkbox.check()
  await expect(notice).toBeVisible()
  await checkbox.uncheck()
  await expect(notice).toHaveCount(0)
  await checkbox.check()
  await expect(notice).toBeVisible()
  await page.getByRole('textbox').fill('Новая задача')
  await page.getByRole('textbox').press('Enter')
  await expect(notice).toHaveCount(0)
  await page.getByRole('button', { name: 'Удалить задачу: Новая задача', exact: true }).click()
  await expect(notice).toHaveCount(0)
  await page.getByRole('button', { name: 'Вернуть', exact: true }).click()
  await expect(notice).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Новая задача', exact: true }).check()
  await expect(notice).toBeVisible()
})
